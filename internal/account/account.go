// Package account handles what a person does with their own account outside a
// session: confirming the e-mail and recovering the password, by e-mail or by
// a link/code a síndico passes on (for example over WhatsApp).
//
// Tokens are random, single-use and stored only as a hash. Asking for a reset
// or a new verification never reveals whether the e-mail has an account.
package account

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/url"
	"strings"
	"sync"
	"time"

	"github.com/victorradael/condoguard/api/internal/middleware"
	pkgemail "github.com/victorradael/condoguard/api/pkg/email"
	"github.com/victorradael/condoguard/api/pkg/mailer"
	"github.com/victorradael/condoguard/api/pkg/password"
)

// What a token is for.
const (
	PurposeReset  = "password_reset"
	PurposeVerify = "email_verify"
)

// Lifetimes.
const (
	// ResetTTL is how long a reset link asked for by the user works.
	ResetTTL = time.Hour
	// VerifyTTL is how long a verification link works.
	VerifyTTL = 24 * time.Hour
	// ManagerTTL is how long a link generated by a síndico works: it travels by chat and may sit unread for a while.
	ManagerTTL = 24 * time.Hour
)

// ErrInvalidToken is returned for a token that is unknown, malformed, used or expired.
var ErrInvalidToken = errors.New("account: invalid or expired token")

// ErrNotMember is returned when a link is asked for an account that is not in the condominium.
var ErrNotMember = errors.New("account: not a member of this condominium")

// ErrValidation signals a rejected password.
var ErrValidation = errors.New("validation error")

// Account is the part of a user the flows need.
type Account struct {
	ID       string
	Email    string
	Username string
	Verified bool
}

// Peek is who a token belongs to.
type Peek struct {
	UserID, Email, Username string
}

// Store persists tokens and applies their effects.
type Store interface {
	// FindByEmail finds the account by its normalised e-mail. ok is false when there is none.
	FindByEmail(ctx context.Context, email string) (a Account, ok bool, err error)
	// Issue stores a token for the account, replacing any unused one of the same purpose.
	Issue(ctx context.Context, userID, purpose string, hash []byte, expires time.Time) error
	// IssueForMember is Issue for an account of the condominium in ctx, on behalf of issuerID.
	// ok is false when the account is not a member.
	IssueForMember(ctx context.Context, userID, purpose string, hash []byte, expires time.Time, issuerID string) (ok bool, err error)
	// Peek says who an unused, unexpired token belongs to (ErrInvalidToken otherwise).
	Peek(ctx context.Context, hash []byte, purpose string) (Peek, error)
	// VerifyEmail spends the token and marks the e-mail as confirmed.
	VerifyEmail(ctx context.Context, hash []byte) (userID string, err error)
	// ResetPassword spends the token, sets the password hash, confirms the e-mail and
	// revokes every refresh token of the account.
	ResetPassword(ctx context.Context, hash []byte, passwordHash string) (userID string, err error)
	// RevokeSessions revokes the refresh tokens of the account, which must be the caller or a member of the condominium in ctx.
	RevokeSessions(ctx context.Context, userID string) error
}

// Service runs the flows.
type Service struct {
	store     Store
	mail      mailer.Sender
	baseURL   string
	revoked   middleware.Revocations
	accessTTL time.Duration
	wg        sync.WaitGroup
}

// New creates the Service. baseURL is where the web app lives (links in the e-mails point there).
func New(store Store, mail mailer.Sender, baseURL string) *Service {
	return &Service{store: store, mail: mail, baseURL: strings.TrimRight(baseURL, "/"), accessTTL: 15 * time.Minute}
}

// WithRevocations makes a password reset also kill the access tokens already issued.
func (s *Service) WithRevocations(r middleware.Revocations, accessTTL time.Duration) *Service {
	s.revoked, s.accessTTL = r, accessTTL
	return s
}

// Wait blocks until the e-mails being sent in the background are done (graceful shutdown, tests).
func (s *Service) Wait() { s.wg.Wait() }

// background runs fn off the request, so that an unknown e-mail and a known
// one take the same time to answer.
func (s *Service) background(fn func(ctx context.Context)) {
	s.wg.Add(1)
	go func() {
		defer s.wg.Done()
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		fn(ctx)
	}()
}

// Link is a token ready to be handed over.
type Link struct {
	Purpose   string    `json:"purpose"`
	Token     string    `json:"token"`
	URL       string    `json:"link"`
	ExpiresAt time.Time `json:"expiresAt"`
}

func (s *Service) link(purpose, token string) string {
	path := "/redefinir-senha"
	if purpose == PurposeVerify {
		path = "/verificar-email"
	}
	return s.baseURL + path + "?token=" + url.QueryEscape(token)
}

// RequestPasswordReset sends a reset link to the e-mail if it has an account.
// It answers the same way for unknown and invalid e-mails.
func (s *Service) RequestPasswordReset(ctx context.Context, rawEmail string) error {
	email, err := pkgemail.Normalize(rawEmail)
	if err != nil {
		return nil
	}
	s.background(func(ctx context.Context) {
		a, ok, err := s.store.FindByEmail(ctx, email)
		if err != nil || !ok {
			if err != nil {
				slog.Error("account: password reset lookup", "error", err)
			}
			return
		}
		link, err := s.issue(ctx, a.ID, PurposeReset, ResetTTL, "")
		if err != nil {
			slog.Error("account: password reset token", "error", err)
			return
		}
		s.deliver(ctx, a.Email, "Redefinição de senha — Condoguard", fmt.Sprintf(
			"Olá, %s.\n\nRecebemos um pedido para redefinir a senha da sua conta no Condoguard.\n\n"+
				"Abra o link abaixo (vale por 1 hora e só pode ser usado uma vez):\n%s\n\n"+
				"Se preferir, informe este código na tela de redefinição: %s\n\n"+
				"Se você não pediu isso, ignore este e-mail: a sua senha continua a mesma.\n", a.Username, link.URL, link.Token))
	})
	return nil
}

// RequestVerification sends a new verification link if the e-mail has an
// account that is not verified yet. It answers the same way otherwise.
func (s *Service) RequestVerification(ctx context.Context, rawEmail string) error {
	email, err := pkgemail.Normalize(rawEmail)
	if err != nil {
		return nil
	}
	s.background(func(ctx context.Context) {
		a, ok, err := s.store.FindByEmail(ctx, email)
		if err != nil || !ok || a.Verified {
			if err != nil {
				slog.Error("account: verification lookup", "error", err)
			}
			return
		}
		s.sendVerification(ctx, a.ID, a.Email, a.Username)
	})
	return nil
}

// SendVerification e-mails a verification link to a freshly created account.
// A failure is logged and not returned: the account exists and the person can ask again.
func (s *Service) SendVerification(ctx context.Context, userID, email, username string) {
	s.background(func(ctx context.Context) { s.sendVerification(ctx, userID, email, username) })
}

func (s *Service) sendVerification(ctx context.Context, userID, email, username string) {
	link, err := s.issue(ctx, userID, PurposeVerify, VerifyTTL, "")
	if err != nil {
		slog.Error("account: verification token", "error", err)
		return
	}
	s.deliver(ctx, email, "Confirme o seu e-mail — Condoguard", fmt.Sprintf(
		"Olá, %s.\n\nConfirme o seu e-mail para entrar no Condoguard. Abra o link abaixo (vale por 24 horas):\n%s\n\n"+
			"Ou informe este código na tela de confirmação: %s\n\n"+
			"Se você não criou esta conta, ignore este e-mail.\n", username, link.URL, link.Token))
}

func (s *Service) issue(ctx context.Context, userID, purpose string, ttl time.Duration, issuerID string) (Link, error) {
	token, hash, err := NewToken()
	if err != nil {
		return Link{}, err
	}
	expires := time.Now().Add(ttl)
	if issuerID == "" {
		err = s.store.Issue(ctx, userID, purpose, hash, expires)
	} else {
		var ok bool
		if ok, err = s.store.IssueForMember(ctx, userID, purpose, hash, expires, issuerID); err == nil && !ok {
			err = ErrNotMember
		}
	}
	if err != nil {
		return Link{}, err
	}
	return Link{Purpose: purpose, Token: token, URL: s.link(purpose, token), ExpiresAt: expires}, nil
}

func (s *Service) deliver(ctx context.Context, to, subject, body string) {
	if err := s.mail.Send(ctx, mailer.Message{To: to, Subject: subject, Body: body}); err != nil {
		slog.Error("account: e-mail not sent", "error", err)
	}
}

// IssueLink makes a link/code for an account of the caller's condominium, to
// be passed on by the caller (a síndico over WhatsApp, for instance). The
// caller's authorization is checked by the caller; the database only issues
// for members of the condominium in ctx.
func (s *Service) IssueLink(ctx context.Context, userID, purpose, issuerID string) (Link, error) {
	if purpose != PurposeReset && purpose != PurposeVerify {
		return Link{}, fmt.Errorf("%w: purpose must be %s or %s", ErrValidation, PurposeReset, PurposeVerify)
	}
	return s.issue(ctx, userID, purpose, ManagerTTL, issuerID)
}

// VerifyEmail confirms the e-mail behind the token.
func (s *Service) VerifyEmail(ctx context.Context, token string) error {
	if !wellFormed(token) {
		return ErrInvalidToken
	}
	_, err := s.store.VerifyEmail(ctx, HashToken(token))
	return err
}

// ResetPassword sets a new password with the token and ends every session of the account.
func (s *Service) ResetPassword(ctx context.Context, token, newPassword string) error {
	if !wellFormed(token) {
		return ErrInvalidToken
	}
	hash := HashToken(token)
	who, err := s.store.Peek(ctx, hash, PurposeReset)
	if err != nil {
		return err
	}
	// Checked before the token is spent: a weak password must not burn the link.
	if err = password.Validate(newPassword, localPart(who.Email), who.Username); err != nil {
		return fmt.Errorf("%w: %v", ErrValidation, err)
	}
	hashed, err := password.Hash(newPassword)
	if err != nil {
		return err
	}
	userID, err := s.store.ResetPassword(ctx, hash, hashed)
	if err != nil {
		return err
	}
	if s.revoked != nil {
		if err = s.revoked.RevokeUser(ctx, userID, time.Now(), s.accessTTL); err != nil {
			return fmt.Errorf("account: revoke access tokens: %w", err)
		}
	}
	return nil
}

func localPart(email string) string {
	if i := strings.IndexByte(email, '@'); i >= 0 {
		return email[:i]
	}
	return email
}
